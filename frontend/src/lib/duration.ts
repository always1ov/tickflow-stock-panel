/**
 * [R245] 天数的**唯一写法**。
 *
 * 用户: 「必须要统一表达, 不能又两种多种表述」(R241) →「我要确定性的显示
 * 多少天」→「候选池显示的天数不正确」。
 *
 * R241 把说法统一成了两个词, 但**只统一了字面**, 没统一"这个数准不准"那一半:
 *
 *     已250天      数出来的, 这一段确实是 250 天
 *     已250天+     **没得数了** —— 撞上了天花板, 真实天数只多不少
 *
 * 系统里每一个"连着几天"都有天花板:
 *
 *     · 回看上限            MAX_LOOKBACK / VERDICT_TAIL, 都是 250
 *     · 取数窗口就这么长     日线批量只取回这么多根
 *     · 长期档暖机           MA120 要 120 根, 更早的日子**算不出来**
 *
 * 撞上任何一堵墙, 报出来的都是**下界**。原来一律不标, 于是下界和准数长得
 * 一模一样 —— 一只磨了一年底的票和一只刚好磨了 66 天的票, 徽标上都印「已66天」。
 *
 * 列很窄, 所以徽标上只用一个 `+`; 悬停里写「以上」(R241 定的, 不再用 `≥`/`超过`)。
 */
export const dayCount = (n: number, capped?: boolean) => `已${n}天${capped ? '+' : ''}`

/** 悬停/正文里的长写法 —— 同一件事, 只是不受列宽约束。 */
export const dayCountLong = (n: number, capped?: boolean) =>
  capped ? `已${n}天以上` : `已${n}天`
